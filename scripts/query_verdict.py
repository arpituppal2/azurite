#!/usr/bin/env python3
"""Format the query-head verdict from the stored evaluation summary.

Every number is read from `summary.json` or recomputed from the per-example
files. This script never evaluates a model and never writes an accuracy.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from azurite.artifacts import sha256_file, verify_arm_records  # noqa: E402


def pct(x: float) -> str:
    return f"{100 * x:.2f}%"


def pp(x: float) -> str:
    return f"{100 * x:+.2f} pp"


def pval(p: float) -> str:
    return "< 1e-300" if p == 0 else f"{p:.3g}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=ROOT / "results/jev_query/eval", type=Path)
    ap.add_argument("--out", default=ROOT / "results/jev_query/eval/VERDICT.md", type=Path)
    args = ap.parse_args()
    summary = json.loads((args.dir / "summary.json").read_text())
    amendment = ROOT / "results/jev_query/PRE_REGISTRATION_AMENDMENT_1.md"
    amendment2 = ROOT / "results/jev_query/PRE_REGISTRATION_AMENDMENT_2.md"
    arms = summary["arms"]
    paired = summary["paired"]
    decision = summary["decision"]
    state = summary["state"]

    # Recompute every arm from its record before quoting it.
    verify_arm_records(args.dir, summary)

    lines = [
        "# VERDICT — message-query attention head on Banking77",
        "",
        "Generated by `scripts/query_verdict.py` from `summary.json` and the",
        "per-example records. Every number below is machine-read.",
        "",
        "## Provenance",
        "",
        f"- protocol: `{summary['protocol']}`",
        f"- pre-registration SHA-256: `{summary['prereg_sha256']}`",
        f"- evaluator amendment 1 SHA-256: `{sha256_file(amendment)}`",
        f"- evaluator amendment 2 SHA-256: `{sha256_file(amendment2)}`",
        f"- input record SHA-256: `{summary['inputs_sha256']}`",
        f"- old head SHA-256: `{summary['heads']['old']['sha256']}`",
        f"- query head SHA-256: `{summary['heads']['query']['sha256']}`",
        f"- rows: {state['n']}; Jev {state['jev_correct']}/{state['n']} = "
        f"{pct(state['jev_accuracy'])}",
        "",
        "## Result",
        "",
        "| arm | n | correct | accuracy | 95% Wilson | diff vs Jev | McNemar p | bootstrap lower |",
        "|---|---:|---:|---:|---|---:|---:|---:|",
    ]
    labels = {
        "old_a0": "old head, message only",
        "old_a2c": "old head, examples (control)",
        "query_a0": "query head, message only",
        "query_a2c": "query head, examples (primary)",
    }
    for name in ("old_a0", "old_a2c", "query_a0", "query_a2c"):
        arm, pair = arms[name], paired[name]
        lo, hi = arm["wilson95"]
        lines.append(
            f"| {labels[name]} | {arm['n']} | {arm['correct']} | "
            f"{pct(arm['accuracy'])} | [{pct(lo)}, {pct(hi)}] | "
            f"{pp(pair['diff_vs_jev'])} | {pval(pair['mcnemar']['p'])} | "
            f"{pp(pair['bootstrap_lower_95'])} |"
        )
    lines += [
        "",
        f"P0 decision: **{decision['verdict']}**.",
        f"Primary accuracy {pct(arms['query_a2c']['accuracy'])}; Jev bar "
        f"{pct(decision['p0_bar'])}; point-estimate meets bar: "
        f"{decision['point_estimate_meets_bar']}; diff {pp(decision['diff_vs_jev'])}; "
        f"McNemar p {pval(decision['mcnemar_p'])}; bootstrap lower "
        f"{pp(decision['bootstrap_lower_95'])}; non-inferior at -2 pp: "
        f"{decision['noninferior_at_minus_2pp']}.",
        "",
        "## Mechanism controls",
        "",
    ]
    for other in ("old_a2c", "query_a0"):
        pair = paired[f"query_a2c_vs_{other}"]
        lines.append(
            f"- query_a2c vs {other}: {pp(pair['diff'])}, "
            f"McNemar p {pval(pair['mcnemar']['p'])}, bootstrap lower "
            f"{pp(pair['bootstrap_lower_95'])}."
        )
    lines += [
        "",
        "Read these controls before the headline. `old_a2c` isolates the head",
        "change under the same complete-example packing; `query_a0` isolates the",
        "example context on the new head. A gain over old_a2c is a pooling gain.",
        "",
        "## What this establishes",
        "",
    ]
    if decision["verdict"].startswith("P0"):
        if "missed" in decision["verdict"]:
            lines += [
                "- The query head does not meet the P0 bar on Banking77.",
                "- The direction and size of the mechanism gain, if any, are the",
                "  controls above; they are not a substitute for the P0 bar.",
            ]
        else:
            lines += [
                "- The query head meets or exceeds the P0 bar on Banking77 on the",
                "  same rows, examples and metric as the public Jev record.",
                "- The fine-tune asymmetry remains: this head saw 4,000 labelled",
                "  rows; Jev's weights saw none.",
            ]
    lines += [
        "- One seed and one head; no seed distribution is claimed.",
        "- The encoder is native 1,024 bytes; this says nothing about a 5,120-byte",
        "  native model or a length-adapted encoder.",
        "",
        "## Next lever if P0 is missed",
        "",
        "The measured next lever is a length-adapted encoder: continue pretraining",
        "or RoPE-scale the 113.47M checkpoint to 5,120 bytes, then train the same",
        "query head with all 24 examples. That is a separate, costed run (a",
        "continued-pretraining pass, not a fine-tune), and it is not in this",
        "record. If the query head does not beat old_a2c, the pooling change is",
        "not the lever, and the next step is data/scale rather than another head.",
        "",
    ]
    args.out.write_text("\n".join(lines))

    manifest = args.dir / "MANIFEST.sha256"
    if manifest.exists():
        kept = [
            line for line in manifest.read_text().splitlines()
            if not line.endswith("./results/jev_query/eval/VERDICT.md")
        ]
        kept = [line for line in kept
                if not line.endswith(("./results/jev_query/PRE_REGISTRATION_AMENDMENT_1.md",
                                      "./results/jev_query/PRE_REGISTRATION_AMENDMENT_2.md"))]
        kept.append(f"{sha256_file(amendment)}  ./results/jev_query/PRE_REGISTRATION_AMENDMENT_1.md")
        kept.append(f"{sha256_file(amendment2)}  ./results/jev_query/PRE_REGISTRATION_AMENDMENT_2.md")
        kept.append(f"{sha256_file(args.out)}  ./results/jev_query/eval/VERDICT.md")
        manifest.write_text("\n".join(kept) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
