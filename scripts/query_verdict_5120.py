#!/usr/bin/env python3
"""Format the 5,120-byte query-head verdict from the stored evaluation summary.

Every number is read from `summary.json` or recomputed from the per-example
files. This script never evaluates a model and never writes an accuracy.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from azurite.artifacts import sha256_file, verify_arm_records  # noqa: E402


def pct(x: float) -> str:
    return f"{100 * x:.2f}%"


def pp(x: float) -> str:
    return f"{100 * x:+.2f} pp"


def pval(p: float) -> str:
    return "< 1e-300" if p == 0 else f"{p:.3g}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=ROOT / "results/jev_query_5120/eval", type=Path)
    ap.add_argument("--out", default=ROOT / "results/jev_query_5120/eval/VERDICT.md", type=Path)
    args = ap.parse_args()
    summary = json.loads((args.dir / "summary.json").read_text())
    arms = summary["arms"]
    paired = summary["paired"]
    decision = summary["decision"]
    state = summary["state"]
    separation = summary["train_test_separation"]
    prereg = ROOT / "results/jev_query_5120/PRE_REGISTRATION.md"
    meta = json.loads((ROOT / "results/jev_query_5120/train_meta.json").read_text())
    native = json.loads((ROOT / "results/jev_query/eval/summary.json").read_text())
    native_arm = native["arms"]["query_a2c"]
    sec = meta["ms_per_step"] / 1000.0

    def hours(seq: int, f: float, steps: int = 3_000) -> float:
        ratio = seq / 5_120
        return steps * sec * (ratio * (1 - f) + ratio ** 2 * f) / 3_600

    short_lo, short_hi = hours(16_384, 0.3) + hours(16_384, 0.3, 1_220), hours(16_384, 0.5) + hours(16_384, 0.5, 1_220)
    long_lo, long_hi = hours(32_768, 0.3) + hours(32_768, 0.3, 1_220), hours(32_768, 0.5) + hours(32_768, 0.5, 1_220)

    verify_arm_records(args.dir, summary)

    labels = {
        "old_a0": "old head, message only (protocol control)",
        "old_a2c": "old head, examples that fit (control)",
        "len_a0": "5,120 joint-fine-tune query head, message only",
        "len_a2c": "5,120 joint-fine-tune query head, all 24 examples (primary)",
    }
    lines = [
        "# VERDICT — 5,120-byte joint-fine-tuned query head on Banking77",
        "",
        "Generated by `scripts/query_verdict_5120.py` from `summary.json` and the",
        "per-example records. Every number below is machine-read.",
        "",
        "## Provenance",
        "",
        f"- protocol: `{summary['protocol']}`",
        "- schedule: Amendment 1 joint fine-tune (encoder and head trained together",
        "  at 5,120 for 3,000 steps from the 1,024-position checkpoint); the separate",
        "  1,220-step masked-LM adaptation was not run",
        f"- pre-registration SHA-256: `{summary['prereg_sha256']}`",
        f"- pre-registration file SHA-256: `{sha256_file(prereg)}`",
        f"- amendment SHA-256: `{summary['amendment_sha256']}`",
        f"- init checkpoint SHA-256 (1,024 positions): `{summary['init_checkpoint']['sha256']}`",
        f"- input record SHA-256: `{summary['inputs_sha256']}`",
        f"- old head SHA-256: `{summary['heads']['old']['sha256']}`",
        f"- query head SHA-256: `{summary['heads']['query']['sha256']}`",
        f"- rows: {state['n']}; Jev {state['jev_correct']}/{state['n']} = "
        f"{pct(state['jev_accuracy'])}",
        "",
        "## Result",
        "",
        "| arm | n | correct | accuracy | 95% Wilson | diff vs Jev | McNemar p | bootstrap lower |",
        "|---|---:|---:|---:|---|---:|---:|---:|",
    ]
    for name in ("old_a0", "old_a2c", "len_a0", "len_a2c"):
        arm, pair = arms[name], paired[name]
        lo, hi = arm["wilson95"]
        lines.append(
            f"| {labels[name]} | {arm['n']} | {arm['correct']} | "
            f"{pct(arm['accuracy'])} | [{pct(lo)}, {pct(hi)}] | "
            f"{pp(pair['diff_vs_jev'])} | {pval(pair['mcnemar']['p'])} | "
            f"{pp(pair['bootstrap_lower_95'])} |"
        )
    lines += [
        "",
        f"P0 decision: **{decision['verdict']}**.",
        f"Primary accuracy {pct(arms['len_a2c']['accuracy'])}; Jev bar "
        f"{pct(decision['p0_bar'])}; point-estimate meets bar: "
        f"{decision['point_estimate_meets_bar']}; diff {pp(decision['diff_vs_jev'])}; "
        f"McNemar p {pval(decision['mcnemar_p'])}; bootstrap lower "
        f"{pp(decision['bootstrap_lower_95'])}; non-inferior at -2 pp: "
        f"{decision['noninferior_at_minus_2pp']}.",
        "",
        "## Mechanism controls",
        "",
    ]
    for other in ("old_a2c", "len_a0", "old_a0"):
        pair = paired[f"len_a2c_vs_{other}"]
        lines.append(
            f"- len_a2c vs {other}: {pp(pair['diff'])}, "
            f"McNemar p {pval(pair['mcnemar']['p'])}, bootstrap lower "
            f"{pp(pair['bootstrap_lower_95'])}."
        )
    lines += [
        "",
        "`old_a0` fixes the rows, labels, Jev vector and metric. `old_a2c` is the",
        "old head under the native complete-example packing; `len_a0` is the new",
        "head without examples. A gain over old_a2c isolates length plus head; a",
        "gain over len_a0 isolates the example context on the new head.",
        "",
        f"Against the message-only old head (`old_a0`, {pct(arms['old_a0']['accuracy'])}), "
        f"the primary arm is {pp(paired['len_a2c_vs_old_a0']['diff'])} "
        f"(exact McNemar {pval(paired['len_a2c_vs_old_a0']['mcnemar']['p'])}). Against the"
        f" native-window query head ({pct(native_arm['accuracy'])}), it is "
        f"{pp(arms['len_a2c']['accuracy'] - native_arm['accuracy'])}.",
        "",
        "## Train/test separation",
        "",
        f"- training rows: {separation['train_n']}; correct {separation['train_correct']} = "
        f"{pct(separation['train_accuracy'])}; final training loss "
        f"{separation['final_training_loss']:.6f}; mean last 50 "
        f"{separation['mean_training_loss_last_50']:.6f}.",
        f"- test rows: {separation['test_n']}; correct {separation['test_correct']} = "
        f"{pct(separation['test_accuracy'])}; test minus train "
        f"{pp(separation['test_minus_train'])}.",
        f"- {separation['note']}",
        "",
        "## What this establishes",
        "",
    ]
    if decision["verdict"] == "P0 missed":
        lines += [
            "- The 5,120-byte joint-fine-tuned query head does not meet the P0 bar",
            "  on all 3,080 official Banking77 rows.",
            "- The controls above show whether the remaining gap is a head/context",
            "  mechanism or an information/scale limit; they do not replace the bar.",
        ]
    else:
        lines += [
            "- The 5,120-byte joint-fine-tuned query head meets or exceeds the P0",
            "  bar on the same rows, examples and metric as the public Jev record.",
            "- The fine-tune asymmetry remains: this head saw 4,000 labelled rows;",
            "  Jev's weights saw none.",
        ]
    lines += [
        "- One seed and one head; no seed distribution is claimed.",
        "- The category definitions are not in this context; this is not a test of",
        "  Jev's 77-definition prompt at a longer window.",
        "",
        "## What next, if the bar is still out of reach",
        "",
        "The next lever is not another head. It is the information budget:",
        "category definitions plus all 24 examples at 16k--32k bytes, preceded by a",
        "separate masked-LM adaptation and a new pre-registration. This arm also",
        "bundles adaptation and head training (amendment 1), so it cannot separate",
        "the example budget from the joint schedule; the negative result is about",
        "the schedule as run as well as about the information.",
        "",
        f"From the measured {sec:.2f} s/step at 5,120 and the attention-scaling",
        f"allowance in GAPS.md, that arm is projected at {short_lo:.1f}--{short_hi:.1f}",
        f"GPU-hours at 16k and {long_lo:.1f}--{long_hi:.1f} at 32k, including a",
        "1,220-step adaptation. If it also misses, the honest statement is that",
        "this model class and budget cannot reach 92.40% on Banking77.",
        "",
    ]
    args.out.write_text("\n".join(lines))

    manifest = args.dir / "MANIFEST.sha256"
    if manifest.exists():
        kept = [line for line in manifest.read_text().splitlines()
                if not line.endswith("./results/jev_query_5120/eval/VERDICT.md")]
        kept.append(f"{sha256_file(args.out)}  ./results/jev_query_5120/eval/VERDICT.md")
        manifest.write_text("\n".join(kept) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
