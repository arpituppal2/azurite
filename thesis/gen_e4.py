#!/usr/bin/env python3
"""Generate the E4 candidate-set table and its prose macros.

The record of authority is ``results/e4_candidate_sweep/SUMMARY.json``, written by
``scripts/e4_summary.py`` after it has verified every per-example record against
its own correctness bits, the pre-registration hash and the checkpoint hash.  This
script only formats that record; it never recomputes an accuracy from a rounded
value and never accepts a task that is absent from the summary.

Outputs:
    thesis/tables/e4.tex          task x width rows with Wilson intervals
    thesis/tables/macros_e4.tex   every E4 number quoted in prose
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "thesis" / "tables"
SUMMARY = ROOT / "results" / "e4_candidate_sweep" / "SUMMARY.json"

LABEL = {"banking77": "Banking77", "clinc_oos": "CLINC150",
         "massive_intent": "MASSIVE intent"}
KEY = {"banking77": "Bank", "clinc_oos": "Clinc", "massive_intent": "Massive"}


def main() -> int:
    doc = json.loads(SUMMARY.read_text())
    tasks = doc["tasks"]
    order = ["banking77", "clinc_oos", "massive_intent"]

    def sci(p: float) -> str:
        mant, exp = f"{p:.2e}".split("e")
        return rf"${float(mant):.2f}\times10^{{{int(exp)}}}$"

    rows = []
    for task in order:
        t = tasks[task]
        k = t["k"]
        p_primary = t["primary"]["mcnemar"]["p"]
        for w in ("2", "8", "32", str(k)):
            c = t["widths"][w]
            delta = "---" if w == str(k) else f"${100 * (c['accuracy'] - t['widths'][str(k)]['accuracy']):+.2f}$"
            pcell = sci(p_primary) if w == "32" else "---"
            rows.append(
                rf"{LABEL[task]} ($K={k}$) & {w} & {100 * c['accuracy']:.2f} & "
                rf"{100 * c['wilson95'][0]:.2f}--{100 * c['wilson95'][1]:.2f} & "
                rf"{c['nll']:.2f} & {delta} & {pcell} \\"
            )

    table = rf"""\begin{{table}}[htbp]
\centering
\footnotesize
\caption{{The candidate-set sweep at 113.47M. Each row is a separate fine-tune of
the same pretrained checkpoint, at the suite's frozen recipe (4{{,}}000
stratified rows, 3{{,}}000 steps, batch 32, LR $10^{{-4}}$, seed 0), differing only
in the number of candidates $|C|$ packed into every training and test row. Test
rows are the same 2{{,}}000 rows at every width. A fixed model restricted to a
sub-bank is not an experiment: with the gold always present, deleting candidates
can only remove wrong argmaxes, so restricted accuracy is guaranteed to be at
least the full-bank accuracy. Width is therefore trained, not simulated. Wilson
intervals are 95\%; NLL is over the sampled candidate set and is not comparable
across widths. Read from \texttt{{results/e4\_candidate\_sweep/SUMMARY.json}};
\texttt{{scripts/e4\_summary.py}} verifies every per-example record before
writing it.}}
\label{{tab:e4}}
\setlength{{\tabcolsep}}{{2.5pt}}
\begin{{tabular}}{{@{{}}lrrrrrr@{{}}}}
\toprule
Task & $|C|$ & Accuracy & 95\% CI & NLL & $\Delta$ vs $K$ & $p$ (32 vs $K$) \\ 
\midrule
""" + "\n".join(rows) + rf"""
\bottomrule
\end{{tabular}}
\par\smallskip
\footnotesize
$\Delta$ is in percentage points against the full-bank arm of the same task; the
$p$ column is the exact two-sided McNemar test for 32 against $K$ on the same
test rows. The full-bank arms are the harness check: the pre-registered tolerance against
the published suite cell is 0.2 points, and a larger deviation is reported as a
discrepancy rather than replaced by the published value.
\end{{table}}
"""
    (OUT / "e4.tex").write_text(table)

    m = ["% generated by thesis/gen_e4.py from results/e4_candidate_sweep — do not edit"]

    def add(name: str, value) -> None:
        m.append(rf"\newcommand{{\{name}}}{{{value}}}")

    add("ETasks", len(order))
    add("EMaxHarnessDelta",
        f"{max(t['harness']['abs_delta_pp'] for t in tasks.values()):.2f}")
    add("EHolds", doc["holds_count"])
    add("EAggregateVerdict", "holds" if doc["aggregate_verdict"] == "holds" else "is falsified")
    add("EMargin", f"{abs(doc['margin_pp']):.1f}")
    add("EPreregSha", doc["prereg_sha256"][:16] + r"\ldots")
    add("ECheckpoint", doc["checkpoint_sha256"][:16] + r"\ldots")
    secs = []
    for t in tasks.values():
        for w, c in t["widths"].items():
            secs.append(c.get("train_seconds", 0.0))
    if all(secs):
        mean_h = sum(secs) / len(secs) / 3600
        add("EArms", len(secs))
        add("EArmHours", f"{mean_h:.2f}")
        add("EFutureHours", f"{24 * mean_h:.1f}")
        add("EFutureBothHours", f"{36 * mean_h:.1f}")
        add("ESweepHours", f"{sum(secs) / 3600:.1f}")
    costs = [abs(t["secondary"]["width2_vs_K"]["delta_pp"]) for t in tasks.values()]
    add("ECostMin", f"{min(costs):.2f}")
    add("ECostMax", f"{max(costs):.2f}")
    costs_2_32 = [100 * (t["widths"]["2"]["accuracy"] - t["widths"]["32"]["accuracy"])
                 for t in tasks.values()]
    add("ECostTwoToThirtyTwoMin", f"{min(costs_2_32):.2f}")
    add("ECostTwoToThirtyTwoMax", f"{max(costs_2_32):.2f}")
    word = {"2": "Two", "8": "Eight", "32": "ThirtyTwo"}
    for task in order:
        t = tasks[task]
        key = KEY[task]
        add(f"E{key}K", str(t["k"]))
        for w, label in (("2", "WTwo"), ("8", "WEight"), ("32", "WThirtyTwo"),
                         (str(t["k"]), "WK")):
            c = t["widths"][w]
            add(f"E{key}{label}", f"{100 * c['accuracy']:.2f}")
            add(f"E{key}{label}Lo", f"{100 * c['wilson95'][0]:.2f}")
            add(f"E{key}{label}Hi", f"{100 * c['wilson95'][1]:.2f}")
        p = t["primary"]
        add(f"E{key}Delta", f"{p['delta_pp']:+.2f}")
        add(f"E{key}Lower", f"{p['lower95_pp']:+.2f}")
        add(f"E{key}P", f"{p['mcnemar']['p']:.2e}")
        add(f"E{key}Verdict", "holds" if p["verdict"] == "holds" else "is falsified")
        h = t["harness"]
        add(f"E{key}HarnessDelta", f"{h['abs_delta_pp']:.2f}")
        add(f"E{key}Published", f"{100 * h['published']:.2f}")
        add(f"E{key}HarnessOK", "yes" if h["reproduces_within_0p2pp"] else "no")
        add(f"E{key}WidthTwo", f"{t['secondary']['width2_vs_K']['delta_pp']:+.2f}")
        add(f"E{key}WidthTwoCost",
            f"{abs(t['secondary']['width2_vs_K']['delta_pp']):.2f}")
        add(f"E{key}WidthEightVsThirtyTwo", f"{t['secondary']['width8_vs_32']['delta_pp']:+.2f}")
        for w in ("2", "8", "32"):
            add(f"E{key}FullKAt{word[w]}", f"{100 * t['widths'][w]['full_k_accuracy']:.2f}")
        add(f"E{key}CostTwoToThirtyTwo",
            f"{100 * (t['widths']['2']['accuracy'] - t['widths']['32']['accuracy']):.2f}")
    (OUT / "macros_e4.tex").write_text("\n".join(m) + "\n")
    print(f"wrote tables/e4.tex and macros_e4.tex; aggregate={doc['aggregate_verdict']} "
          f"holds={doc['holds_count']}/{len(order)}")
    for task in order:
        p = tasks[task]["primary"]
        print(f"  {task:15s} K={tasks[task]['k']:3d} acc32={100*p['acc32']:.2f} "
              f"accK={100*p['accK']:.2f} d={p['delta_pp']:+.2f} "
              f"lower={p['lower95_pp']:+.2f} {p['verdict']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
