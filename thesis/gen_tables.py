#!/usr/bin/env python3
"""Generate every table and every inline number in the dissertation from results.

Why this is a script and not copied numbers
-------------------------------------------
A thesis whose tables are hand-copied from a terminal is a thesis that cannot be
checked. This project has already produced two numbers that could not be
re-derived and one that was off by a factor of two; both survived because they
were typed into prose instead of read from a file.

So: tables are `.tex` fragments emitted here, and prose refers to figures through
macros whose values come from the same source. If a run is missing, the macro
says `pending` and the table row says `pending` — the document degrades honestly
instead of silently keeping a stale number.

Outputs (all in `thesis/tables/`):
    macros.tex        inline figures used in prose
    corpus.tex        corpus composition
    fixed_d.tex       the fixed-data size sweep
    protocol.tex      sampled vs exhaustive evaluation
    throughput.tex    measured tok/s and VRAM per rung
    e2.tex            token-budget trajectory at the large rung
    transfer.tex      fine-tuning transfer matrix
    iso_dn.tex        matched-D/N scaling table (self-filling)
    context.tex       context-length table (self-filling)

Usage:
    python3 thesis/gen_tables.py            # from the repo root
"""

from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "thesis" / "tables"
PRETRAIN = ROOT / "results" / "pretrain"
TRANSFER = ROOT / "results" / "transfer"
RECOVERED = ROOT / "results" / "recovered_20261028" / "results" / "transfer"
RECOVERED_PRETRAIN = ROOT / "results" / "recovered_20261028" / "results" / "pretrain"
DVS = ROOT / "results" / "decode_vs_score"
TOKENS = ROOT / "data" / "tokens"

PENDING = r"\emph{pending}"

# The six sampled draws are the surviving protocol record. They are printed in
# Table 1; the exhaustive replicate that would justify a reduction claim was lost
# with the first sandbox, so the generated macros do not invent a ratio.
PROTOCOL_DRAWS = [("1234", 64, 2.3834, 19610), ("1234", 256, 2.3934, 78553),
                  ("7", 64, 2.1682, 19555), ("7", 256, 2.2861, 78351),
                  ("99", 64, 2.5202, 19818), ("99", 256, 2.3139, 78611)]


def tex_int(n: float | int) -> str:
    return f"{int(n):,}".replace(",", "{,}")


def tex_num(x: float, places: int = 4) -> str:
    return f"{x:.{places}f}"


def load(path: Path) -> dict | None:
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def heldout(run: str) -> dict | None:
    """Best available exhaustive score for a run directory."""
    d = run_dir(run)
    for name in ("full.json", "full_seq1024.json", "heldout_full_A.json"):
        rec = load(d / name)
        if rec:
            return rec
    summ = load(d / "summary.json")
    if summ and "heldout" in summ:
        h = dict(summ["heldout"])
        h.setdefault("params", summ.get("params"))
        h.setdefault("tokens_seen", summ.get("tokens_seen"))
        h.setdefault("protocol", "sampled-64")
        return h
    return None


def train_loss(run: str) -> float | None:
    p = run_dir(run) / "train.jsonl"
    if not p.exists():
        return None
    rows = []
    for line in p.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    if not rows:
        return None
    tail = [r["loss"] for r in rows[-40:]]
    return sum(tail) / len(tail)


def write(name: str, body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(body, encoding="utf-8")


# ---------------------------------------------------------------- macros

def build_macros() -> None:
    m: list[str] = ["% generated by thesis/gen_tables.py — do not edit by hand"]
    manifest = load(TOKENS / "byte_corpus_v2.manifest.json")
    if manifest:
        m.append(rf"\newcommand{{\CorpusTokens}}{{{tex_int(manifest['tokens_u16'])}}}")
        m.append(rf"\newcommand{{\CorpusGB}}{{{manifest['bytes'] / 1e9:.2f}}}")
        m.append(rf"\newcommand{{\CorpusSha}}{{\texttt{{{manifest['sha256'][:16]}\ldots}}}}")
        m.append(rf"\newcommand{{\CorpusDocs}}{{{tex_int(sum(v['docs'] for v in manifest['sources'].values()))}}}")
        sp = manifest["split"]
        m.append(rf"\newcommand{{\HoldoutPct}}{{{sp['heldout_fraction'] * 100:.2f}}}")
        m.append(rf"\newcommand{{\HoldoutTokens}}{{{tex_int(sp['heldout_bytes'])}}}")
        m.append(rf"\newcommand{{\TrainTokens}}{{{tex_int(sp['n_train'])}}}")
        # The 4B ceiling is an arithmetic argument, not a run. These macros keep
        # the prose's D/N figures tied to the corpus manifest instead of a
        # hand-transcribed token count.
        tokens = manifest["tokens_u16"]
        four_b = 4_000_000_000
        m.append(rf"\newcommand{{\FourBDN}}{{{tokens / four_b:.2f}}}")
        m.append(rf"\newcommand{{\FourBTokensB}}{{{20 * four_b / 1e9:.1f}}}")
        m.append(rf"\newcommand{{\FourBGPUHours}}{{{tex_int((20 * four_b) / 1000 / 3600)}}}")
        m.append(rf"\newcommand{{\LargeDN}}{{{tokens / 113_465_856:.1f}}}")
        m.append(rf"\newcommand{{\FourBFactor}}{{{(tokens / 113_465_856) / (tokens / four_b):.1f}}}")
    else:
        for k in ("Tokens", "GB", "Docs", "HoldoutPct", "HoldoutTokens", "TrainTokens"):
            m.append(rf"\newcommand{{\Corpus{k}}}{{{PENDING}}}")
        m.append(rf"\newcommand{{\CorpusSha}}{{{PENDING}}}")

    # protocol spread: old sampled draws are recorded in the protocol cell and
    # in results/pretrain/_snap_x5/heldout_full_{A,B}.json
    a = load(PRETRAIN / "_snap_x5" / "heldout_full_A.json")
    b = load(PRETRAIN / "_snap_x5" / "heldout_full_B.json")
    old_spread = max(d[2] for d in PROTOCOL_DRAWS) - min(d[2] for d in PROTOCOL_DRAWS)
    m.append(rf"\newcommand{{\ProtoOldSpread}}{{{old_spread:.4f}}}")
    m.append(rf"\newcommand{{\ProtoPositions}}{{{tex_int(max(d[3] for d in PROTOCOL_DRAWS))}}}")
    if a and b:
        new_spread = abs(a["bits_per_byte"] - b["bits_per_byte"])
        m.append(rf"\newcommand{{\ProtoNewSpread}}{{{new_spread:.4f}}}")
        m.append(rf"\newcommand{{\ProtoRatio}}{{{old_spread / max(new_spread, 1e-9):.0f}}}")
    else:
        for k in ("NewSpread", "Ratio"):
            m.append(rf"\newcommand{{\Proto{k}}}{{{PENDING}}}")

    # fixed-D sweep figures quoted in prose
    big = heldout("l1_large_byte")
    if big:
        tl = train_loss("l1_large_byte")
        m.append(rf"\newcommand{{\LargeHeldout}}{{{tex_num(big['bits_per_byte'])}}}")
        if tl:
            m.append(rf"\newcommand{{\LargeTrainBits}}{{{tex_num(tl / math.log(2), 3)}}}")
            m.append(rf"\newcommand{{\LargeGap}}{{{big['bits_per_byte'] / (tl / math.log(2)):.0f}}}")
    if not any("LargeHeldout" in x for x in m):
        for k in ("Heldout", "TrainBits", "Gap"):
            m.append(rf"\newcommand{{\Large{k}}}{{{PENDING}}}")

    write("macros.tex", "\n".join(m) + "\n")


