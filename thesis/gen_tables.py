def build_fixed_d() -> None:
    rows = []
    for label, run, params in FIXED_D:
        h = heldout(run)
        tl = train_loss(run)
        full = any((PRETRAIN / run / name).exists()
                   for name in ("full.json", "full_seq1024.json", "heldout_full_A.json"))
        source = "exhaustive" if full else ("sampled" if h else "lost")
        if not h or not tl:
            rows.append(rf"{label} & {tex_int(params)} & & & {PENDING} & & {source} " + "\\\\")
            continue
        tb = tl / math.log(2)
        dn = (h.get("tokens_seen") or 100e6) / params
        rows.append(
            rf"{label} & {tex_int(params)} & {dn:.1f} & {tb:.3f} & "
            rf"\textbf{{{tex_num(h['bits_per_byte'])}}} & {h['bits_per_byte'] / tb:.1f}$\times$ & {source} \\"
        )
    body = r"""\begin{table}[htbp]
\centering
\caption{Fixed-budget scores surviving on this checkout (100M tokens, 30\%
mask). The source column is the evaluation protocol that produced the score:
\emph{exhaustive} where a full-score file survived, \emph{sampled} where only a
summary survived, and \emph{lost} where the run directory was reclaimed. Sampled
and exhaustive rows are not comparable, and the mid/large cells were lost with
the first sandbox; no U-shape is claimed from this table. The generalisation gap
is held-out over train loss, both in bits/byte. Generated by
\texttt{thesis/gen\_tables.py}.}
\label{tab:fixed-d}
\begin{tabular}{lrrrrrr}
\toprule
Rung & Parameters & $D/N$ & Train & Held-out & Gap & Source \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("fixed_d.tex", body)


def build_protocol() -> None:
    a = load(PRETRAIN / "_snap_x5" / "heldout_full_A.json")
    b = load(PRETRAIN / "_snap_x5" / "heldout_full_B.json")
    rows = []
    for i, (seed, k, val, pos) in enumerate(PROTOCOL_DRAWS):
        head = r"\multirow{6}{*}{sampled}" if i == 0 else ""
        rows.append(rf"{head} & seed {seed}, $k={k}$ & {val:.4f} & {tex_int(pos)} \\")
    rows.append(r"\midrule")
    if a and b:
        rows.append(rf"\multirow{{2}}{{*}}{{exhaustive}} & run A & {a['bits_per_byte']:.4f} & {tex_int(a['scored_tokens'])} \\")
        rows.append(rf" & run B & {b['bits_per_byte']:.4f} & {tex_int(b['scored_tokens'])} \\")
    else:
        rows.append(rf"\multirow{{2}}{{*}}{{exhaustive}} & run A & {PENDING} & \\")
        rows.append(rf" & run B & {PENDING} & \\")
    body = r"""\begin{table}[htbp]
\centering
\caption{One frozen checkpoint (large, step 10{,}000) under the sampled protocol.
The six draws span more than the largest effect the ladder was built to measure.
The exhaustive replicates are marked pending because the run directory was lost
with the first sandbox; their reduction is not claimed in this build.}
\label{tab:protocol}
\begin{tabular}{llrr}
\toprule
Protocol & Condition & Bits/byte & Scored positions \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("protocol.tex", body)


def build_throughput() -> None:
    rows = []
    for label, run, params in FIXED_D:
        drv = load(PRETRAIN / run / "driver.json")
        summ = load(PRETRAIN / run / "summary.json")
        tok = (drv or {}).get("tokens_target") or (summ or {}).get("tokens_seen")
        wall = (drv or {}).get("elapsed_total_s") or (summ or {}).get("seconds")
        peak = ((summ or {}).get("memory") or {}).get("peak_cuda_alloc_gib")
        if not tok or not wall:
            rows.append(rf"{label} & {tex_int(params)} & & & & \\")
            continue
        peak_cell = f"{peak:.1f}" if peak else "--"
        rows.append(
            rf"{label} & {tex_int(params)} & {tok / 1e6:.0f}M & {wall:.0f} & "
            rf"{tok / wall:,.0f} & {peak_cell} \\"
        )
    body = r"""\begin{table}[htbp]
\centering
\caption{Measured throughput and peak resident memory. Wall clock is
end-to-end for the run, so it includes checkpoint writes and the exhaustive
evaluation, not just the optimiser loop.}
\label{tab:throughput}
\begin{tabular}{lrrrrr}
\toprule
Rung & Parameters & Tokens & Wall (s) & tok/s & Peak GiB \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("throughput.tex", body)


