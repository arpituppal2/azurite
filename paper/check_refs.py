#!/usr/bin/env python3
"""Check the paper bibliography against the paper's citations.

Structural checks always run.  ``--online`` additionally asks Crossref about
DOIs and fetches each URL; a 403 is recorded as bot-blocked rather than dead,
because publisher and DOI front ends routinely reject scripted requests.

    python paper/check_refs.py
    python paper/check_refs.py --online
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEX = ROOT / "paper" / "azurite.tex"
BIB = ROOT / "paper" / "refs.bib"
OUT = ROOT / "paper" / "REFERENCE_CHECK.md"
UA = "azurite-paper-reference-check/1.0 (mailto:research@example.invalid)"


def entries(text: str) -> list[dict[str, str]]:
    out = []
    for match in re.finditer(r"@(\w+)\{([^,]+),(.*?)\n\}", text, re.S):
        kind, key, body = match.group(1), match.group(2).strip(), match.group(3)
        fields = {"kind": kind, "key": key}
        for field in re.finditer(r"(\w+)\s*=\s*\{(.*?)\}\s*,?", body, re.S):
            fields[field.group(1).lower()] = re.sub(r"\s+", " ", field.group(2)).strip()
        out.append(fields)
    return out


def cited(text: str) -> set[str]:
    keys = set()
    for match in re.finditer(r"\\cite[pt]?\{([^}]*)\}", text):
        keys.update(item.strip() for item in match.group(1).split(","))
    return keys


def fetch(url: str) -> tuple[int, str]:
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "*/*"})
    try:
        with urllib.request.urlopen(req, timeout=25) as response:
            return response.status, response.geturl()
    except urllib.error.HTTPError as error:
        return error.code, url
    except Exception as error:  # noqa: BLE001 - the report needs the reason
        return 0, f"{type(error).__name__}: {error}"


def online(fields: dict[str, str]) -> tuple[str, str]:
    doi = fields.get("doi", "")
    url = fields.get("url", "")
    if doi:
        api = "https://api.crossref.org/works/" + urllib.parse.quote(doi)
        status, final = fetch(api)
        if status == 200:
            return "DOI resolves", "Crossref 200"
        if status:
            return "DOI returned HTTP %d" % status, final
        return "DOI check failed", final
    if url:
        status, final = fetch(url)
        if status == 200:
            return "URL resolves", "HTTP 200"
        if status == 403:
            return "URL bot-blocked", "HTTP 403 (not evidence of absence)"
        if status:
            return "URL returned HTTP %d" % status, final
        return "URL check failed", final
    return "no locator", ""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--online", action="store_true")
    args = ap.parse_args()
    text = TEX.read_text()
    bib = entries(BIB.read_text())
    used = cited(text)
    keys = {entry["key"] for entry in bib}
    problems: list[str] = []
    if used - keys:
        problems.append("cited but absent: " + ", ".join(sorted(used - keys)))
    if keys - used:
        problems.append("present but uncited: " + ", ".join(sorted(keys - used)))
    for entry in bib:
        for field in ("title", "author", "year"):
            if not entry.get(field):
                problems.append(f"{entry['key']}: missing {field}")
        if not (entry.get("doi") or entry.get("url")):
            problems.append(f"{entry['key']}: no DOI or URL")

    rows = []
    for entry in bib:
        verdict, detail = online(entry) if args.online else ("not checked", "")
        rows.append((entry["key"], entry.get("year", ""), verdict, detail))
        if args.online:
            time.sleep(0.25)

    lines = [
        "# Reference check",
        "",
        "Generated by `paper/check_refs.py`.",
        "",
        f"- citations used: {len(used)}",
        f"- bibliography entries: {len(keys)}",
        f"- structural problems: {len(problems)}",
        "",
    ]
    if problems:
        lines += ["## Problems", ""] + [f"- {problem}" for problem in problems] + [""]
    lines += [
        "| key | year | check | detail |",
        "|---|---:|---|---|",
        *[f"| `{key}` | {year} | {verdict} | {detail} |" for key, year, verdict, detail in rows],
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}; {len(problems)} structural problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
